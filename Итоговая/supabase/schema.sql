-- Проверка формы регистрации до обращения к Supabase Auth: ответ 422
-- с ошибками по полям вместо общего «Database error saving new user»
create function public.signup_errors(p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  e jsonb := '{}';
  v_login text := lower(btrim(coalesce(p->>'username', '')));
  v_password text := coalesce(p->>'password', '');
  problems text[] := '{}';
  v jsonb;
begin
  if v_login !~ '^[a-z0-9_.-]{3,30}$' then
    e := e || '{"username": "От 3 до 30 символов: латинские буквы, цифры, точка, дефис, _"}';
  elsif exists (select 1 from public.profiles pr where pr.username = v_login) then
    e := e || '{"username": "Такой логин уже занят"}';
  end if;
  if char_length(v_password) < 8 then problems := problems || 'не короче 8 символов'::text; end if;
  if v_password !~ '\d' then problems := problems || 'хотя бы одна цифра'::text; end if;
  if v_password !~ '[^A-Za-zА-Яа-яЁё0-9[:space:]]' then problems := problems || 'хотя бы один специальный символ'::text; end if;
  if cardinality(problems) > 0 then
    e := e || jsonb_build_object('password', 'Пароль: ' || array_to_string(problems, ', '));
  end if;
  v := public.viewer_errors(jsonb_build_object('lastName', p->'lastName', 'firstName', p->'firstName', 'email', p->'email'), null);
  return e || (select coalesce(jsonb_object_agg(key, value), '{}') from jsonb_each(v) where key in ('lastName', 'firstName', 'email'));
end $$;

-- Новый пользователь Supabase Auth → зритель с картой «Базовый» на 4
-- посещения и профиль с ролью «зритель». Данные формы приходят в
-- raw_user_meta_data. Учётные записи из seed.sql помечены seed=true:
-- их профили seed.sql создаёт сам
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}');
  vid integer;
begin
  if meta ? 'seed' then
    return new;
  end if;
  -- Пароль уже проверен и захеширован Supabase Auth: здесь вместо него
  -- подставлен заведомо подходящий, чтобы проверить остальные поля
  perform public.validation_failed(public.signup_errors(
    meta || jsonb_build_object('email', new.email, 'password', 'x1#xxxxx')));
  insert into public.viewers (last_name, first_name, email)
  values (btrim(meta->>'lastName'), btrim(meta->>'firstName'), new.email)
  returning id into vid;
  insert into public.cards (viewer_id, number, tariff, visits_left)
  values (vid, public.next_card_number(), 'Базовый', 4);
  insert into public.profiles (auth_id, username, email, first_name, last_name, role, viewer_id)
  values (new.id, lower(btrim(meta->>'username')), new.email, btrim(meta->>'firstName'), btrim(meta->>'lastName'), 'viewer', vid);
  return new;
end $$;

create trigger kinoteka_on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Роль и блокировку меняет только администратор, и не самому себе.
-- Остальные поля профиля через API не меняются
create function public.guard_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if public.is_trusted() then
    return new;
  end if;
  perform public.require_perm('users.manage');
  if old.auth_id = auth.uid() then
    raise exception using errcode = 'PT409', message = 'Нельзя изменить роль или заблокировать самого себя.';
  end if;
  if new.role not in (select code from public.roles) then
    perform public.validation_failed('{"role": "Неизвестная роль"}');
  end if;
  if (new.id, new.auth_id, new.username, new.email, new.first_name, new.last_name, new.viewer_id)
     is distinct from (old.id, old.auth_id, old.username, old.email, old.first_name, old.last_name, old.viewer_id) then
    raise exception using errcode = 'PT403', message = 'Изменять можно только роль и блокировку.';
  end if;
  return new;
end $$;

create trigger a_guard before update on public.profiles
  for each row execute function public.guard_profile();

-- Список пользователей и смена роли или блокировки — функциями, а не
-- прямым запросом к profiles: без права users.manage они отвечают 403,
-- а не пустым списком, который вернуло бы правило RLS
create function public.list_users() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.require_perm('users.manage');
  return coalesce((select jsonb_agg(to_jsonb(p) - 'auth_id' order by p.id) from public.profiles p), '[]');
end $$;

create function public.update_user(p_id integer, p_role text default null, p_blocked boolean default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  r jsonb;
begin
  perform public.require_perm('users.manage');
  if not exists (select 1 from public.profiles where id = p_id) then
    raise exception using errcode = 'PT404', message = format('Пользователь с номером %s не найден(а).', p_id);
  end if;
  if (select auth_id from public.profiles where id = p_id) = auth.uid() then
    raise exception using errcode = 'PT409', message = 'Нельзя изменить роль или заблокировать самого себя.';
  end if;
  if p_role is not null and p_role not in (select code from public.roles) then
    perform public.validation_failed('{"role": "Неизвестная роль"}');
  end if;
  update public.profiles set role = coalesce(p_role, role), blocked = coalesce(p_blocked, blocked)
  where id = p_id
  returning to_jsonb(profiles) - 'auth_id' into r;
  return r;
end $$;

