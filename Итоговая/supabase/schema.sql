create function public.movie_errors(p jsonb, p_id integer) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  e jsonb := '{}';
  this_year integer := extract(year from now());
  title text := btrim(coalesce(p->>'title', ''));
  original text := btrim(coalesce(p->>'originalTitle', ''));
  lic text := btrim(coalesce(p->>'licenseNumber', ''));
  ids integer[];
  missing integer[];
begin
  if title = '' then e := e || '{"title": "Обязательное поле"}';
  elsif char_length(title) > 100 then e := e || '{"title": "Не длиннее 100 символов"}'; end if;
  if original = '' then e := e || '{"originalTitle": "Обязательное поле"}';
  elsif char_length(original) > 100 then e := e || '{"originalTitle": "Не длиннее 100 символов"}'; end if;

  if jsonb_typeof(p->'year') is distinct from 'number' then e := e || '{"year": "Введите целое число"}';
  elsif public.int_error((p->>'year')::numeric::int, 1895, this_year + 3) is not null then
    e := e || jsonb_build_object('year', public.int_error((p->>'year')::numeric::int, 1895, this_year + 3));
  end if;
  if jsonb_typeof(p->'duration') is distinct from 'number' then e := e || '{"duration": "Введите целое число"}';
  elsif public.int_error((p->>'duration')::numeric::int, 1, 600) is not null then
    e := e || jsonb_build_object('duration', public.int_error((p->>'duration')::numeric::int, 1, 600));
  end if;
  if jsonb_typeof(p->'rating') is distinct from 'number' or (p->>'rating')::numeric not between 0 and 10 then
    e := e || '{"rating": "Допустимо от 0 до 10"}';
  end if;

  if lic !~ '^\d{9}$' then e := e || '{"licenseNumber": "Ровно 9 цифр"}';
  elsif exists (select 1 from public.movies where license_number = lic and id is distinct from p_id) then
    e := e || '{"licenseNumber": "Фильм с таким номером удостоверения уже есть в каталоге"}';
  end if;

  if jsonb_typeof(p->'studioId') is distinct from 'number' then e := e || '{"studioId": "Выберите киностудию"}';
  elsif not exists (select 1 from public.studios where id = (p->>'studioId')::int and deleted_at is null) then
    e := e || jsonb_build_object('studioId', format('Киностудия с номером %s не найдена', p->>'studioId'));
  end if;

  ids := array(select distinct jsonb_array_elements_text(coalesce(p->'directorIds', '[]'))::int);
  if cardinality(ids) < 1 then e := e || '{"directorIds": "Выберите хотя бы одного режиссёра"}';
  elsif cardinality(ids) > 3 then e := e || '{"directorIds": "Не больше 3"}';
  else
    missing := array(select x from unnest(ids) x where not exists (select 1 from public.directors where id = x and deleted_at is null));
    if cardinality(missing) > 0 then
      e := e || jsonb_build_object('directorIds', 'Не найдены записи с номерами: ' || array_to_string(missing, ', '));
    end if;
  end if;

  ids := array(select distinct jsonb_array_elements_text(coalesce(p->'genreIds', '[]'))::int);
  if cardinality(ids) < 1 then e := e || '{"genreIds": "Выберите хотя бы один жанр"}';
  elsif cardinality(ids) > 5 then e := e || '{"genreIds": "Не больше 5"}';
  else
    missing := array(select x from unnest(ids) x where not exists (select 1 from public.genres where id = x and deleted_at is null));
    if cardinality(missing) > 0 then
      e := e || jsonb_build_object('genreIds', 'Не найдены записи с номерами: ' || array_to_string(missing, ', '));
    end if;
  end if;
  return e;
end $$;

-- Создание (p_id = null) или изменение фильма вместе со связями — одной
-- транзакцией. security invoker: права проверяет триггер a_guard
create function public.save_movie(p jsonb, p_id integer default null) returns jsonb
language plpgsql set search_path = public as $$
declare
  mid integer;
begin
  perform public.require_perm('catalog.edit');
  perform public.validation_failed(public.movie_errors(p, p_id));

  if p_id is null then
    insert into public.movies (title, original_title, year, duration, rating, license_number, studio_id)
    values (btrim(p->>'title'), btrim(p->>'originalTitle'), (p->>'year')::int, (p->>'duration')::int,
            (p->>'rating')::numeric, btrim(p->>'licenseNumber'), (p->>'studioId')::int)
    returning id into mid;
  else
    update public.movies set
      title = btrim(p->>'title'), original_title = btrim(p->>'originalTitle'),
      year = (p->>'year')::int, duration = (p->>'duration')::int, rating = (p->>'rating')::numeric,
      license_number = btrim(p->>'licenseNumber'), studio_id = (p->>'studioId')::int
    where id = p_id
    returning id into mid;
    if mid is null then
      raise exception using errcode = 'PT404', message = format('Фильм с номером %s не найден(а).', p_id);
    end if;
    delete from public.movie_directors where movie_id = mid;
    delete from public.movie_genres where movie_id = mid;
  end if;

  -- Повторы в списке убираются, порядок выбора сохраняется в position
  insert into public.movie_directors (movie_id, director_id, position)
  select mid, v::int, min(o)::smallint from jsonb_array_elements_text(p->'directorIds') with ordinality t(v, o) group by v;
  insert into public.movie_genres (movie_id, genre_id, position)
  select mid, v::int, min(o)::smallint from jsonb_array_elements_text(p->'genreIds') with ordinality t(v, o) group by v;

  return (select to_jsonb(m) from public.movies_view m where m.id = mid);
end $$;

