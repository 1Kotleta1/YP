create index movie_directors_director_idx on public.movie_directors (director_id);

create table public.movie_genres (
  movie_id integer references public.movies (id) on delete cascade,
  genre_id integer references public.genres (id) on delete restrict,
  position smallint not null default 0,
  primary key (movie_id, genre_id)
);
create index movie_genres_genre_idx on public.movie_genres (genre_id);

