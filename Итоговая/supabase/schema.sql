-- =====================================================================
-- «Кинотека» — схема базы данных для Supabase (PostgreSQL)
--
-- Выполняется в Supabase → SQL Editor целиком, затем seed.sql.
-- Повторный запуск пересоздаёт схему с нуля (данные удаляются).
--
-- REST API строит сама платформа (PostgREST): каждая таблица и
-- представление доступны по адресу /rest/v1/<имя>, функции — по адресу
-- /rest/v1/rpc/<имя>. Серверного кода нет: права проверяют правила RLS
-- и триггеры, данные — ограничения таблиц и триггеры проверки.
--
-- Коды ответов. Функция или триггер, поднявшие ошибку с кодом PTxxx,
-- дают HTTP-ответ с кодом xxx:
--   PT403 — роль не позволяет операцию;
--   PT409 — нарушена целостность (удаление связанной записи и т. п.);
--   PT422 — ошибки по полям, в details — JSON {"поле": "текст"}.
-- =====================================================================

