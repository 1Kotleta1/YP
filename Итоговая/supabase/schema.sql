-- Каталог: читать может любая роль; записи из корзины видит только
-- администратор. Записывать может любой вошедший — право на конкретную
-- операцию проверяет триггер a_guard и отвечает 403 с понятным текстом
do $$
declare
  t text;
begin
  foreach t in array array['genres', 'studios', 'directors', 'movies'] loop
