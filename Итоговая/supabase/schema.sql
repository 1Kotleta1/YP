-- В корзину и обратно — функциями. Прямой PATCH deleted_at не подходит:
-- запись, убранная в корзину, перестаёт быть видна менеджеру по правилу
-- RLS, и PostgreSQL отклонил бы такое изменение. Права и запрет удалять
-- студию со ссылающимися фильмами проверяет тот же триггер a_guard
create function public.move_to_trash(p_table text, p_ids integer[]) returns integer
language plpgsql security definer set search_path = public as $$
declare
  n integer;
begin
  if p_table not in ('movies', 'directors', 'genres', 'studios', 'viewers') then
    raise exception using errcode = 'PT404', message = format('Нет такой коллекции: %s', p_table);
  end if;
  perform public.require_perm(case p_table when 'viewers' then 'viewers.manage' else 'catalog.edit' end);
  execute format('update public.%I set deleted_at = now() where id = any($1) and deleted_at is null', p_table) using p_ids;
  get diagnostics n = row_count;
  return n;
end $$;

create function public.restore_from_trash(p_table text, p_ids integer[]) returns integer
language plpgsql security definer set search_path = public as $$
declare
  n integer;
begin
  if p_table not in ('movies', 'directors', 'genres', 'studios', 'viewers') then
    raise exception using errcode = 'PT404', message = format('Нет такой коллекции: %s', p_table);
  end if;
  perform public.require_perm('records.restore');
  execute format('update public.%I set deleted_at = null where id = any($1) and deleted_at is not null', p_table) using p_ids;
  get diagnostics n = row_count;
  return n;
end $$;

