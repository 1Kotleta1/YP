-- Отметка посещения по карте: 409, если посещений не осталось
create function public.register_visit(p_viewer_id integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v public.viewers_view;
begin
  perform public.require_perm('visits.mark');
  select * into v from public.viewers_view where id = p_viewer_id;
  if v.id is null then
    raise exception using errcode = 'PT404', message = format('Зритель с номером %s не найден(а).', p_viewer_id);
  end if;
  if v.deleted_at is not null then
    raise exception using errcode = 'PT409',
      message = format('Зритель «%s %s» в корзине — посещение отметить нельзя.', v.first_name, v.last_name);
  end if;
  if v.card_visits_left <= 0 then
    raise exception using errcode = 'PT409',
      message = format('По карте %s не осталось посещений. Продлите тариф «%s», чтобы пропустить зрителя.', v.card_number, v.card_tariff);
  end if;
  update public.cards set visits_left = visits_left - 1 where viewer_id = v.id;
  insert into public.card_events (viewer_id, type, delta, by_user)
  values (v.id, 'visit', -1, (select username from public.profiles where auth_id = auth.uid()));
  return (select to_jsonb(x) from public.viewers_view x where x.id = v.id);
end $$;

-- Своя карта зрителя и последние 20 событий по ней
create function public.my_card() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  vid integer;
  result jsonb;
begin
  perform public.require_perm('card.own');
  select viewer_id into vid from public.profiles where auth_id = auth.uid();
  select to_jsonb(v) into result from public.viewers_view v where v.id = vid and v.deleted_at is null;
  if result is null then
    raise exception using errcode = 'PT404', message = 'Карта зрителя не найдена. Обратитесь к менеджеру кинотеки.';
  end if;
  return jsonb_build_object(
    'viewer', result,
    'history', coalesce((
      select jsonb_agg(jsonb_build_object('type', type, 'delta', delta, 'at', at, 'by', by_user) order by at desc)
      from (select * from public.card_events where viewer_id = vid order by at desc limit 20) h
    ), '[]'));
end $$;

-- Продление абонемента: +4 / +8 / +12 посещений по тарифу, не больше 100
create function public.renew_my_card() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  vid integer;
  c public.cards;
  add integer;
begin
  perform public.require_perm('card.own');
  select viewer_id into vid from public.profiles where auth_id = auth.uid();
  select * into c from public.cards where viewer_id = vid;
  if c.viewer_id is null then
    raise exception using errcode = 'PT404', message = 'Карта зрителя не найдена. Обратитесь к менеджеру кинотеки.';
  end if;
  add := case c.tariff when 'Стандарт' then 8 when 'Премиум' then 12 else 4 end;
  if c.visits_left + add > 100 then
    raise exception using errcode = 'PT409',
      message = format('Абонемент уже продлён: на карте %s посещений, больше 100 быть не может.', c.visits_left);
  end if;
  update public.cards set visits_left = visits_left + add where viewer_id = vid;
  insert into public.card_events (viewer_id, type, delta, by_user)
  values (vid, 'renew', add, (select username from public.profiles where auth_id = auth.uid()));
  return public.my_card();
end $$;

