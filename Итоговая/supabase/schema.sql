-- ---------------------------------------------------------------- каталог

create table public.genres (
  id          integer generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 30),
  category    text not null check (category in ('Игровое кино', 'Анимация', 'Документальное')),
  description text not null default '' check (char_length(description) <= 300),
  deleted_at  timestamptz
);
-- Название жанра уникально без учёта регистра
create unique index genres_name_key on public.genres (lower(name));

create table public.studios (
  id           integer generated by default as identity primary key,
  name         text not null check (char_length(name) between 1 and 60),
  country      text not null check (char_length(country) between 1 and 50),
  founded_year integer not null check (founded_year >= 1880),
  deleted_at   timestamptz
);

create table public.directors (
  id         integer generated by default as identity primary key,
  last_name  text not null check (char_length(last_name) between 1 and 50),
  first_name text not null check (char_length(first_name) between 1 and 50),
  country    text not null check (char_length(country) between 1 and 50),
  birth_year integer not null check (birth_year >= 1850),
  deleted_at timestamptz
);

create table public.movies (
  id             integer generated by default as identity primary key,
  title          text not null check (char_length(title) between 1 and 100),
  original_title text not null check (char_length(original_title) between 1 and 100),
  year           integer not null check (year >= 1895),
  duration       integer not null check (duration between 1 and 600),
  rating         numeric(3, 1) not null check (rating between 0 and 10),
  -- Номер прокатного удостоверения: ровно 9 цифр, уникален в каталоге
  license_number text not null unique check (license_number ~ '^\d{9}$'),
  -- Многие к одному: студию со ссылающимися фильмами удалить нельзя
  studio_id      integer not null references public.studios (id) on delete restrict,
  deleted_at     timestamptz
);
create index movies_studio_id_idx on public.movies (studio_id);

-- Многие ко многим: фильм — режиссёры (1–3), фильм — жанры (1–5).
-- position сохраняет порядок, в котором их выбрали в форме
create table public.movie_directors (
  movie_id    integer references public.movies (id) on delete cascade,
  director_id integer references public.directors (id) on delete restrict,
  position    smallint not null default 0,
