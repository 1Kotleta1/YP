-- ---------------------------------------------------------------- представления

-- Фильм со списками режиссёров и жанров. security_invoker: правила RLS
-- таблиц действуют и при чтении через представление
create view public.movies_view with (security_invoker = on) as
select
  m.*,
  coalesce((select array_agg(d.director_id order by d.position) from public.movie_directors d where d.movie_id = m.id), '{}') as director_ids,
  coalesce((select array_agg(g.genre_id order by g.position) from public.movie_genres g where g.movie_id = m.id), '{}') as genre_ids
from public.movies m;

-- Зритель вместе с картой: по полям карты можно искать и сортировать
create view public.viewers_view with (security_invoker = on) as
select
  v.*,
  c.number                             as card_number,
  c.tariff                             as card_tariff,
  c.visits_left                        as card_visits_left,
  to_char(c.issued_at, 'DD.MM.YYYY')   as card_issued_at
from public.viewers v
left join public.cards c on c.viewer_id = v.id;

-- ---------------------------------------------------------------- права

-- Роль вошедшего пользователя. Берётся из таблицы profiles по
-- идентификатору из подписанного токена (auth.uid()), а не из того,
-- что прислал клиент. Заблокированный пользователь роли не имеет
create function public.app_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where auth_id = auth.uid() and not blocked
$$;

create function public.has_perm(p text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.role_permissions where role = public.app_role() and permission = p)
$$;

-- Запросы из SQL Editor и с ключом service_role идут без токена
-- пользователя: им проверки прав не нужны (так загружается seed.sql)
create function public.is_trusted() returns boolean
language sql stable as $$
  select coalesce(auth.role(), '') not in ('authenticated', 'anon')
$$;

create function public.require_perm(p text) returns void
language plpgsql stable security definer set search_path = public as $$
declare
  r text := public.app_role();
begin
  if public.is_trusted() or public.has_perm(p) then
    return;
  end if;
  raise exception using
    errcode = 'PT403',
    message = format('Недостаточно прав: «%s» не разрешено роли «%s».',
                     (select title from public.permissions where code = p),
                     coalesce((select title from public.roles where code = r), 'гость'));
end $$;

create function public.validation_failed(errors jsonb) returns void
language plpgsql immutable as $$
begin
  if errors <> '{}'::jsonb then
    raise exception using errcode = 'PT422', message = 'Ошибка валидации', detail = errors::text;
  end if;
end $$;

-- ---------------------------------------------------------------- помощники проверок

create function public.movies_word(n integer) returns text
language sql immutable as $$
  select case
    when n % 10 = 1 and n % 100 <> 11 then 'фильм'
    when n % 10 between 2 and 4 and (n % 100 < 12 or n % 100 > 14) then 'фильма'
    else 'фильмов'
  end
$$;

create function public.is_person_name(v text) returns boolean
language sql immutable as $$
  select v ~ '^[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё'' -]*$'
$$;

-- Текст ошибки для целого числа вне диапазона, иначе null
create function public.int_error(v integer, lo integer, hi integer) returns text
language sql immutable as $$
  select case
    when v is null then 'Введите целое число'
    when v < lo or v > hi then format('Допустимо от %s до %s', lo, hi)
  end
$$;

-- ---------------------------------------------------------------- триггеры каталога и зрителей

-- Права на запись и целостность при удалении. TG_ARGV[0] — право на
-- изменение: catalog.edit для каталога, viewers.manage для зрителей
create function public.guard_catalog() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  edit_perm text := tg_argv[0];
  n integer;
  example text;
begin
  if public.is_trusted() then
    return coalesce(new, old);
  end if;

  if tg_op = 'INSERT' then
    perform public.require_perm(edit_perm);
    new.deleted_at := null;
    return new;
  end if;

  if tg_op = 'UPDATE' then
    if old.deleted_at is not null and new.deleted_at is null then
      perform public.require_perm('records.restore');
    else
      perform public.require_perm(edit_perm);
    end if;
    -- В корзину: время ставит сервер, а не клиент
    if old.deleted_at is null and new.deleted_at is not null then
      new.deleted_at := now();
      if tg_table_name = 'studios' then
        select count(*), min(title) into n, example from public.movies where studio_id = old.id;
        if n > 0 then
          raise exception using errcode = 'PT409', message = format(
            'Нельзя удалить киностудию: на неё %s %s %s (например, «%s»). Сначала укажите этим фильмам другую студию.',
            case when n % 10 = 1 and n % 100 <> 11 then 'ссылается' else 'ссылаются' end, n, public.movies_word(n), example);
        end if;
      end if;
    elsif old.deleted_at is not null and new.deleted_at is not null then
      new.deleted_at := old.deleted_at;
    end if;
    return new;
  end if;

  -- DELETE — удаление навсегда
  perform public.require_perm('records.hardDelete');
  if tg_table_name = 'studios' then
    select count(*), min(title) into n, example from public.movies where studio_id = old.id;
    if n > 0 then
      raise exception using errcode = 'PT409', message = format(
        'Нельзя удалить киностудию: на неё %s %s %s (например, «%s»). Сначала укажите этим фильмам другую студию.',
        case when n % 10 = 1 and n % 100 <> 11 then 'ссылается' else 'ссылаются' end, n, public.movies_word(n), example);
    end if;
  elsif tg_table_name = 'directors' then
    select count(*) into n from public.movie_directors where director_id = old.id;
    if n > 0 then
      raise exception using errcode = 'PT409', message = format(
        'Нельзя удалить режиссёра навсегда: связанных фильмов — %s. Запись можно убрать в корзину.', n);
    end if;
  elsif tg_table_name = 'genres' then
    select count(*) into n from public.movie_genres where genre_id = old.id;
    if n > 0 then
      raise exception using errcode = 'PT409', message = format(
        'Нельзя удалить жанр навсегда: связанных фильмов — %s. Запись можно убрать в корзину.', n);
    end if;
  end if;
  return old;
end $$;

-- Пробелы по краям текстовых полей убираются до проверок
create function public.normalize_catalog() returns trigger
language plpgsql as $$
begin
  if tg_table_name = 'genres' then
    new.name := btrim(new.name); new.category := btrim(new.category); new.description := btrim(coalesce(new.description, ''));
  elsif tg_table_name = 'studios' then
    new.name := btrim(new.name); new.country := btrim(new.country);
  elsif tg_table_name = 'directors' then
    new.last_name := btrim(new.last_name); new.first_name := btrim(new.first_name); new.country := btrim(new.country);
  end if;
  return new;
end $$;

-- Проверки по полям: тексты ошибок те же, что у формы в приложении.
-- Ключи — имена полей модели клиента
create function public.validate_director() returns trigger
language plpgsql as $$
declare
  e jsonb := '{}';
  this_year integer := extract(year from now());
begin
  if coalesce(new.last_name, '') = '' then e := e || '{"lastName": "Обязательное поле"}';
  elsif char_length(new.last_name) > 50 then e := e || '{"lastName": "Не длиннее 50 символов"}';
  elsif not public.is_person_name(new.last_name) then e := e || '{"lastName": "Только буквы, дефис и пробел"}';
  end if;
  if coalesce(new.first_name, '') = '' then e := e || '{"firstName": "Обязательное поле"}';
  elsif char_length(new.first_name) > 50 then e := e || '{"firstName": "Не длиннее 50 символов"}';
  elsif not public.is_person_name(new.first_name) then e := e || '{"firstName": "Только буквы, дефис и пробел"}';
  end if;
  if coalesce(new.country, '') = '' then e := e || '{"country": "Обязательное поле"}';
  elsif char_length(new.country) > 50 then e := e || '{"country": "Не длиннее 50 символов"}';
  end if;
  if public.int_error(new.birth_year, 1850, this_year - 10) is not null then
    e := e || jsonb_build_object('birthYear', public.int_error(new.birth_year, 1850, this_year - 10));
  end if;
  perform public.validation_failed(e);
  return new;
end $$;

create function public.validate_genre() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  e jsonb := '{}';
begin
  if coalesce(new.name, '') = '' then e := e || '{"name": "Обязательное поле"}';
  elsif char_length(new.name) > 30 then e := e || '{"name": "Не длиннее 30 символов"}';
  elsif exists (select 1 from public.genres where lower(name) = lower(new.name) and id <> new.id) then
    e := e || '{"name": "Такой жанр уже есть"}';
  end if;
  if new.category is null or new.category not in ('Игровое кино', 'Анимация', 'Документальное') then
    e := e || '{"category": "Выберите категорию"}';
  end if;
  if char_length(new.description) > 300 then e := e || '{"description": "Не длиннее 300 символов"}'; end if;
  perform public.validation_failed(e);
  return new;
end $$;

create function public.validate_studio() returns trigger
language plpgsql as $$
declare
  e jsonb := '{}';
begin
  if coalesce(new.name, '') = '' then e := e || '{"name": "Обязательное поле"}';
  elsif char_length(new.name) > 60 then e := e || '{"name": "Не длиннее 60 символов"}';
  end if;
  if coalesce(new.country, '') = '' then e := e || '{"country": "Обязательное поле"}';
  elsif char_length(new.country) > 50 then e := e || '{"country": "Не длиннее 50 символов"}';
  end if;
  if public.int_error(new.founded_year, 1880, extract(year from now())::int) is not null then
    e := e || jsonb_build_object('foundedYear', public.int_error(new.founded_year, 1880, extract(year from now())::int));
  end if;
  perform public.validation_failed(e);
  return new;
end $$;

