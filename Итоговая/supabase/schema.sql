create function public.viewer_errors(p jsonb, p_id integer) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  e jsonb := '{}';
  card jsonb := coalesce(p->'card', '{}');
  v_last text := btrim(coalesce(p->>'lastName', ''));
  v_first text := btrim(coalesce(p->>'firstName', ''));
  v_email text := btrim(coalesce(p->>'email', ''));
  v_phone text := btrim(coalesce(p->>'phone', ''));
  num text := upper(btrim(coalesce(card->>'number', '')));
begin
  if v_last = '' then e := e || '{"lastName": "Обязательное поле"}';
  elsif char_length(v_last) > 50 then e := e || '{"lastName": "Не длиннее 50 символов"}';
  elsif not public.is_person_name(v_last) then e := e || '{"lastName": "Только буквы, дефис и пробел"}'; end if;
  if v_first = '' then e := e || '{"firstName": "Обязательное поле"}';
  elsif char_length(v_first) > 50 then e := e || '{"firstName": "Не длиннее 50 символов"}';
  elsif not public.is_person_name(v_first) then e := e || '{"firstName": "Только буквы, дефис и пробел"}'; end if;

  if v_email !~ '^[\w.+-]+@[\w-]+(\.[\w-]+)*\.[A-Za-zА-Яа-я]{2,}$' then
    e := e || '{"email": "Неверный адрес почты, пример: name@mail.ru"}';
  elsif exists (select 1 from public.viewers v where lower(v.email) = lower(v_email) and v.id is distinct from p_id) then
    e := e || '{"email": "Зритель с такой почтой уже зарегистрирован"}';
  end if;
  if v_phone <> '' and v_phone !~ '^\+7\d{10}$' then e := e || '{"phone": "Формат: +7 и 10 цифр"}'; end if;

  -- Ключи ошибок вложенной карты — через точку, как путь к полю в JSON
  if p ? 'card' then
    if num !~ '^KT-\d{6}$' then e := e || '{"card.number": "Формат KT-123456"}';
    elsif exists (select 1 from public.cards where number = num and viewer_id is distinct from p_id) then
      e := e || '{"card.number": "Карта с таким номером уже выдана"}';
    end if;
    if coalesce(card->>'tariff', '') not in ('Базовый', 'Стандарт', 'Премиум') then
      e := e || '{"card.tariff": "Выберите тариф"}';
    end if;
    if jsonb_typeof(card->'visitsLeft') is distinct from 'number' then e := e || '{"card.visitsLeft": "Введите целое число"}';
    elsif public.int_error((card->>'visitsLeft')::numeric::int, 0, 100) is not null then
      e := e || jsonb_build_object('card.visitsLeft', public.int_error((card->>'visitsLeft')::numeric::int, 0, 100));
    end if;
    if coalesce(card->>'issuedAt', '') !~ '^\d{2}\.\d{2}\.\d{4}$' then
      e := e || '{"card.issuedAt": "Формат ДД.ММ.ГГГГ"}';
    end if;
  end if;
  return e;
end $$;

create function public.save_viewer(p jsonb, p_id integer default null) returns jsonb
language plpgsql set search_path = public as $$
declare
  vid integer;
  card jsonb := p->'card';
begin
  perform public.require_perm('viewers.manage');
  perform public.validation_failed(public.viewer_errors(p, p_id));

  if p_id is null then
    insert into public.viewers (last_name, first_name, email, phone)
    values (btrim(p->>'lastName'), btrim(p->>'firstName'), btrim(p->>'email'), btrim(coalesce(p->>'phone', '')))
    returning id into vid;
  else
    update public.viewers set
      last_name = btrim(p->>'lastName'), first_name = btrim(p->>'firstName'),
      email = btrim(p->>'email'), phone = btrim(coalesce(p->>'phone', ''))
    where id = p_id
    returning id into vid;
    if vid is null then
      raise exception using errcode = 'PT404', message = format('Зритель с номером %s не найден(а).', p_id);
    end if;
  end if;

  insert into public.cards (viewer_id, number, tariff, visits_left, issued_at)
  values (vid, upper(btrim(card->>'number')), card->>'tariff', (card->>'visitsLeft')::int,
          to_date(card->>'issuedAt', 'DD.MM.YYYY'))
  on conflict (viewer_id) do update set
    number = excluded.number, tariff = excluded.tariff,
    visits_left = excluded.visits_left, issued_at = excluded.issued_at;

  return (select to_jsonb(v) from public.viewers_view v where v.id = vid);
end $$;

